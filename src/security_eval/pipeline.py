"""Connect generated artifacts to the three analyzer contracts with isolated candidate execution."""
import json
from pathlib import Path

from .analyzers.dynamic import DockerPytestAnalyzer
from .analyzers.static import ASTAnalyzer, BanditAnalyzer
from .contracts import validate, write_json
from .generation import digest


def load_candidate(run_dir: Path) -> tuple[Path, dict, str]:
    """Return (code path, sample, run_id) for a verified, successfully generated candidate."""
    record = json.loads((run_dir / "generation.json").read_text(encoding="utf-8"))
    validate("generation", record)
    if record["status"] != "generated":
        raise ValueError("Evaluation requires a successfully generated candidate")
    sample = json.loads((run_dir / "sample.json").read_text(encoding="utf-8"))
    validate("sample", sample)
    if sample["sample_id"] != record["sample_id"]:
        raise ValueError("Sample identity mismatch")
    code = (run_dir / record["code_file"]).resolve()
    if not code.is_relative_to(run_dir.resolve()):
        raise ValueError("Candidate must be inside its generation directory")
    if digest(code.read_bytes()) != record["code_sha256"]:
        raise ValueError("Candidate hash mismatch; use the original generated bytes")
    return code, sample, record["request_sha256"] + ":" + record["code_sha256"]


def evaluate(run_dir: Path, out: Path) -> list[dict]:
    code, sample, run_id = load_candidate(run_dir)
    out.mkdir(parents=True, exist_ok=False)
    results = []
    analyzers = (
        BanditAnalyzer(out),
        ASTAnalyzer(out),
        DockerPytestAnalyzer(evidence_dir=out / "pytest-docker"),
    )
    for analyzer in analyzers:
        result = analyzer.analyze(code, sample, run_id)
        validate("analysis", result)
        write_json(out / (result["tool"] + ".json"), result)
        results.append(result)
    return results
